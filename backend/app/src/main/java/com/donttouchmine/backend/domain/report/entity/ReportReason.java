package com.donttouchmine.backend.domain.report.entity;

/**
 * 신고 사유. 클라이언트가 이 중에서 고릅니다.
 *
 * <p>고정 목록인 이유는 운영자가 분류할 수 있어야 하기 때문입니다. 자유 텍스트만 받으면
 * 같은 일을 열 사람이 열 가지로 적고, 무엇이 많이 일어나는지 셀 수 없습니다.
 * 대신 목록만으로는 판단할 맥락이 없어서 메모를 함께 받습니다.
 *
 * <p><b>이름을 그대로 DB 에 담습니다.</b> 값을 지우거나 이름을 바꾸면 이미 쌓인 행이
 * 읽을 수 없는 값을 갖게 됩니다. 늘리는 것은 안전하고, 줄이는 것은 마이그레이션이
 * 필요합니다.
 */
public enum ReportReason {

    /** 욕설, 비하, 괴롭힘. */
    ABUSE,

    /** 부정행위. */
    CHEATING,

    /** 도배, 광고. */
    SPAM,

    /** 부적절한 닉네임. */
    INAPPROPRIATE_NAME,

    /** 위 어디에도 없음. 메모를 함께 받는 것이 특히 중요한 값입니다. */
    OTHER
}
