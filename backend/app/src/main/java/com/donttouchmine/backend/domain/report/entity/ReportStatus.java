package com.donttouchmine.backend.domain.report.entity;

/**
 * 신고 한 건이 검토를 거쳤는지.
 *
 * <p>보았는지만 표시하는 두 값(안 봄/봄)으로는 부족합니다. <b>실제로 문제였는지</b>를
 * 남겨야 무고성 신고를 가려낼 수 있습니다. 어떤 사람이 낸 신고가 전부 기각이면 그 사람이
 * 문제인데, 봤다는 사실만 남기면 그것을 셀 수 없습니다.
 *
 * <p>조치를 경고와 정지로 더 나누지 않습니다. 그것은 제재가 무엇인지 정해질 때 제재 쪽에
 * 남을 값이고, 여기는 "이 신고를 어떻게 마무리했는가"만 답합니다.
 */
public enum ReportStatus {

    /** 아직 아무도 보지 않았습니다. 신고가 들어오면 이 값입니다. */
    PENDING,

    /** 보았고 실제 문제였습니다. */
    ACTIONED,

    /** 보았고 조치할 것이 없었습니다. */
    DISMISSED
}
