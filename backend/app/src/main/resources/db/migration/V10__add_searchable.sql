-- 지금까지는 가입한 사람이 모두 검색되고 빠질 방법이 없었습니다.
--
-- <DEFAULT TRUE 는 이미 있는 행을 위한 것입니다.>
-- ALTER 가 도는 순간 기존 사용자 전원이 이 값을 받습니다. FALSE 로 두면 그 한 문장으로
-- 모두가 검색에서 사라지고 친구 추가가 통째로 멈춥니다. 새 컬럼은 기존 행의 동작을
-- 바꾸지 않는 값으로 시작해야 합니다.
--
-- 앞으로 들어올 행에는 이 기본값이 쓰이지 않습니다. User 엔티티가 필드를 true 로
-- 초기화해서 JPA 의 INSERT 에 값이 항상 실려 갑니다. 그래서 이 값을 FALSE 로 바꿔도
-- 새 계정을 만드는 테스트는 통과합니다. 지키는 것은 UserSearchApiTest 의
-- 스키마 기본값 검사입니다.
--
-- TINYINT(1) 이 아니라 BOOLEAN 으로 적었지만 MySQL 에서 같은 것입니다. 읽는 사람에게
-- 뜻이 분명한 쪽을 씁니다.
--
-- 인덱스를 붙이지 않습니다. 검색 쿼리는 ix_users_nickname_lower 로 접두사를 좁힌 뒤
-- 남은 몇 행에서 이 값을 보므로, 여기에 인덱스를 두어도 탈 일이 없습니다. 값이 둘뿐이라
-- 선택도가 낮아 옵티마이저가 고르지도 않습니다.
ALTER TABLE users
    ADD COLUMN searchable BOOLEAN NOT NULL DEFAULT TRUE;
