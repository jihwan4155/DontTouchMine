-- 닉네임을 대소문자를 구분해서 다루도록 바꿉니다.
-- Player와 player를 서로 다른 닉네임으로 쓰기로 정했습니다.
--
-- V1은 서버 기본 콜레이션(utf8mb4_0900_ai_ci)을 그대로 물려받아 두 값을 같은 것으로
-- 취급했습니다. V1 파일의 주석은 그때 기준이라 지금과 다릅니다. 이미 적용된
-- 마이그레이션을 고치면 Flyway 체크섬이 어긋나 기동이 막히므로 손대지 않고,
-- 바뀐 규칙은 이 파일에 적습니다.
--
-- as_cs는 accent sensitive, case sensitive입니다. utf8mb4_bin이 아니라 이쪽을 쓰는
-- 이유는 bin이 코드포인트를 바이트로 비교해서, 눈에 같아 보이는 한글이 조합 방식에
-- 따라 다른 값이 되기 때문입니다. as_cs는 유니코드 정렬 규칙을 따르면서 대소문자만
-- 구분합니다.
--
-- 컬럼 콜레이션이 바뀌면 uk_users_nickname 인덱스는 MySQL이 다시 만듭니다.
-- 기존 데이터가 충돌할 일은 없습니다. 지금까지는 더 엄격한 규칙(대소문자 무시)이
-- 걸려 있었으므로, 대소문자만 다른 두 행이 애초에 존재할 수 없었습니다.
--
--
-- 알아둘 것: 닉네임 검색도 함께 대소문자를 구분하게 됩니다.
--
-- 친구 찾기에서 LIKE 'player%'로 조회하면 Player는 걸리지 않습니다. 검색만
-- 대소문자를 무시하게 하려고 쿼리에 COLLATE를 붙이면 컬럼과 콜레이션이 달라져
-- uk_users_nickname을 타지 못하고 전체 스캔이 됩니다. 검색 기능을 붙일 때는
-- 소문자로 정규화한 생성 컬럼에 인덱스를 따로 두는 쪽을 검토하세요.
ALTER TABLE users
    MODIFY nickname VARCHAR(32)
        CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_as_cs NOT NULL;
