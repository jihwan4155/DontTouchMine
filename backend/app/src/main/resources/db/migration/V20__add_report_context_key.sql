-- 신고는 한 경기에 상대마다 한 번 (S15P21D205-1017).
--
-- V9 는 같은 사람을 여러 번 신고하는 것을 일부러 막지 않았습니다. 횟수가 운영자에게 신호가 된다는
-- 이유였는데, 실제로는 한 사람이 같은 상대를 연타해 건수를 부풀리는 쪽이 문제였습니다. 그래서
-- "한 경기에 같은 상대는 한 번" 으로 바꿉니다. 여러 경기에 걸쳐 쌓이는 횟수는 여전히 신호이고,
-- 운영자 도구가 건수와 신고한 사람 수를 나눠 보는 것도 그대로 의미가 있습니다.
--
-- context_key 는 클라이언트가 만드는 "어느 경기인가" 표식입니다. 방 코드와 그 방에서 본 경기 수로
-- 만들며(예: 7K2M9P#2), 서버는 뜻을 해석하지 않고 같은지만 봅니다. 신고자마다 값이 달라도 됩니다 -
-- 유니크 키가 신고자를 포함하므로 자기 자신과만 겹치지 않으면 됩니다.
--
-- NULL 은 옛 클라이언트가 키 없이 보낸 것입니다. MySQL 유니크 인덱스는 NULL 을 서로 다른 값으로
-- 보므로 여기서는 잡히지 않고, ReportService 가 24시간 규칙으로 대신 막습니다. 기존 행은 전부 NULL 이라
-- 이 마이그레이션이 기존 데이터에 걸릴 일은 없습니다.
--
-- 숨긴 신고(deleted_at)도 유니크에 그대로 잡힙니다. 운영자가 숨겼다고 같은 경기에 다시 신고할 수
-- 있게 되면 숨김이 "다시 신고해 달라" 는 신호가 됩니다. 완전 삭제하면 행이 없어져 다시 가능합니다.
ALTER TABLE user_reports
    ADD COLUMN context_key VARCHAR(64) NULL AFTER memo,
    ADD UNIQUE KEY uk_user_reports_pair_context (reporter_seq, reported_seq, context_key);
