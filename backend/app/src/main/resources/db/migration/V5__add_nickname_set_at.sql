-- 사용자가 닉네임을 직접 정했는지 기록합니다.
--
-- 발급은 멱등해서 같은 기기가 다시 부르면 200을 돌려줍니다. 그래서 클라이언트는
-- 첫 실행만 201로 구분할 수 있고, 두 번째부터는 "닉네임을 아직 안 정했다"를 알 수
-- 없습니다. 입력 화면에서 그냥 끄고 나간 사용자가 정확히 이 경우에 걸립니다.
--
-- 불리언이 아니라 NULL 가능한 시각으로 둡니다. friendships.accepted_at이 이미
-- "NULL이면 아직 일어나지 않았다"는 방식을 쓰고 있어 같은 관습을 따릅니다. 비용은
-- 같은데 언제 정했는지가 함께 남습니다.
--
-- 기존 행을 채우지 않습니다. 이 컬럼이 생기는 시점에 users는 비어 있었고, 행이
-- 있었더라도 전부 자동 생성 닉네임이라 NULL이 맞는 값입니다.
--
-- 값은 첫 변경에서만 채웁니다. 매번 갱신하면 "정한 시각"이 아니라 "마지막으로 바꾼
-- 시각"이 되어 컬럼 이름과 내용이 어긋납니다. 마지막 변경 시각은 updated_at이 이미
-- 들고 있습니다.
ALTER TABLE users
    ADD COLUMN nickname_set_at CHAR(14) NULL AFTER nickname;
