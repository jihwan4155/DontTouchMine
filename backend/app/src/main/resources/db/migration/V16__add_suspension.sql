-- 운영자가 계정을 정지할 수 있게 합니다 (S15P21D205-923).
--
-- 신고는 상대에게 아무 일도 일으키지 않습니다. V8 이 차단을 걷어내고 그 자리를 신고로
-- 대체했을 때의 결정이고, 지금도 그대로입니다. 그래서 신고를 아무리 많이 받아도
-- 운영자가 할 수 있는 일이 기록을 검토하는 것뿐이었습니다. 그 끝에 둘 손을 만듭니다.
--
-- NULL 이 "정상"입니다. V15 의 deleted_at 과 같은 규약입니다. 반대로 두면
-- (suspended BOOLEAN NOT NULL DEFAULT FALSE) 언제 정지했는지가 남지 않는데, 잘못
-- 정지한 것을 되돌릴 때와 "언제부터 못 들어왔나"를 묻는 문의에 시각이 유일한 단서입니다.
--
-- 형식은 다른 시각 컬럼과 같은 CHAR(14) UTC 입니다(yyyyMMddHHmmss). 이 스키마의 시각은
-- 전부 이 모양이고, 여기만 DATETIME 으로 두면 TimeProvider 를 쓰지 못합니다.
--
-- 사유를 함께 둡니다. 시각만 남기면 나중에 본 사람이 왜 정지됐는지 알 수 없고, 해제해도
-- 되는지 판단할 근거가 없습니다. 길이는 신고 메모(200)와 맞춥니다 - 같은 화면에서
-- 신고 내용을 보고 적는 값이라 더 길 이유가 없습니다.
--
-- 기한은 두지 않습니다. 정지와 해제 두 상태뿐이고 해제는 운영자가 누릅니다. 기한을 두면
-- "지금 정지 중인가"를 물을 때마다 시각을 비교해야 하고, 그 비교가 틀리면 풀려야 할
-- 사람이 안 풀리거나 그 반대가 됩니다. 필요해지면 컬럼 하나를 더하는 일입니다.

ALTER TABLE users
    ADD COLUMN suspended_at     CHAR(14)     NULL AFTER searchable,
    ADD COLUMN suspended_reason VARCHAR(200) NULL AFTER suspended_at;

-- 인덱스를 두지 않습니다.
--
-- 이 컬럼을 읽는 곳은 계정 발급과 요청마다 도는 정지 검사인데, 둘 다 public_id 나
-- 기기 식별자로 행 하나를 먼저 집습니다. 그 행의 컬럼을 보는 것이라 인덱스가 할 일이
-- 없습니다. "정지된 사람 목록"을 뽑는 화면이 생기면 그때가 인덱스를 볼 때입니다.
